#!/usr/bin/env bash
# ---------------------------------------------------------------------------
# The Phase 1 exit gate (plan "Phase 1 testing / exit gate", design PHASE1_GATE): ONE deterministic replay of
# the whole thin chain from the recorded bag, every stage into one gate directory, then one verdict.
#
#   infra/scripts/phase1.sh [OUT_ROOT]              FULL: the exit gate / evidence run (clean tree),
#                                                    default OUT_ROOT = evaluation/runs/phase1/exit_gate
#   infra/scripts/phase1.sh --premerge [OUT_ROOT]   PRE-MERGE (D49): same chain on the working tree, but the
#                                                    render is REUSED from build/render_cache/<package sha256>
#                                                    and only if this run's package is byte-identical to one a
#                                                    full run rendered; otherwise it stops and asks for a full
#                                                    run. Default OUT_ROOT = build/premerge. ~20 min, no network.
#
#   0. build + the full ctest suite; the protocol tests (CollabProtocol.*, Serialization.*) on their own
#   1. 1.6 sim_collab twice, in parallel, from the same bag: clean (+ 1.7 spool) and --inject-faults 1;
#      then the fault-identity check (duplicates / out-of-order are idempotent, §15.3 / §37.7)
#   2. 1.7 recon: prepare -> remote GPU render (Kaggle, D44) -> score
#   3. 1.8 mission: merged, agent 0 alone, agent 1 alone + mission_eval
#   4. 1.9 report (the §30.2 gate)    5. 1.10 console chain check
#   6. analysis.phase1_gate: the I1 condition, the §4 contracts, every stage verdict, and the determinism
#      comparison against the committed per-item evidence -> gate.yaml + gate.txt (exit 1 on FAIL)
#
# Small outputs land in OUT_ROOT/<scene>-<UTC>/ (committable); the spool, fused cloud, render package and
# renders stay in build/phase1_gate/<same id>/ with their sha256 in recon/<run>/checksums.sha256.
# Evidence must come from a clean tree; DIRTY_OK=1 allows a dev full run. A full run stores its renders in the
# render cache (renders are a deterministic function of the package: sha-identical across Kaggle sessions, D48). Needs Docker and a Kaggle token
# (~/.kaggle). Wall time ~40 min (sim_collab ~20, Kaggle ~15 incl. the gsplat JIT build).
# ---------------------------------------------------------------------------
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT"
S=infra/scripts
REC=evaluation/runs/phase1/sim_record/ci_tiny_0-20261001T133914Z/raw
SCENE=$REC/scene
mode=full
if [ "${1:-}" = --premerge ]; then mode=premerge; shift; fi
if [ "$mode" = full ]; then out_root="${1:-evaluation/runs/phase1/exit_gate}"; else out_root="${1:-build/premerge}"; fi
CACHE=build/render_cache

die() { echo "phase1.sh: $*" >&2; exit 1; }
dirty="$(git status --porcelain -- . ':!docs' ':!IDEA.md' ':!graphify-out' ':!evaluation/runs' | grep -q . \
  && echo true || echo false)"
[ "$dirty" = false ] || [ "$mode" = premerge ] || [ "${DIRTY_OK:-0}" = 1 ] || die "dirty tree (evidence needs a clean commit; DIRTY_OK=1 for dev)"
[ -d "$REC/rec" ] && [ -f "$SCENE/scene.json" ] || die "missing the recording $REC"
commit="$(git rev-parse HEAD)"
scene_id="$(sed -nE 's/.*"scene_id": *"([^"]+)".*/\1/p' "$SCENE/scene.json" | head -1)"
[ -n "$scene_id" ] || die "no scene_id in $SCENE/scene.json"
id="$scene_id-$(date -u +%Y%m%dT%H%M%SZ)"
G="$out_root/$id" BIG="build/phase1_gate/$id"
mkdir -p "$G/sim_collab" "$G/recon" "$G/mission" "$G/report" "$BIG"
log() { echo "[$(date -u +%H:%M:%S)] $*" | tee -a "$G/gate.log"; }
one() { local m=("$@"); [ "${#m[@]}" -eq 1 ] && [ -e "${m[0]}" ] || die "expected exactly one match, got: ${m[*]}"; echo "${m[0]}"; }
env_run="ARIADNE_GIT_COMMIT=$commit ARIADNE_GIT_DIRTY=$dirty"
bin=/work/build/docker/cpp/runtime
{
  echo "# Phase 1 exit gate $id (generated by infra/scripts/phase1.sh; every stage below ran in this order)"
  echo "commit: $commit  dirty: $dirty  mode: $mode"
} > "$G/command.txt"
echo "$mode" > "$G/mode.txt"
cmd() { echo "$*" >> "$G/command.txt"; }

# --- 0. build + tests ---------------------------------------------------------------------------------------
log "0. build + full ctest"
# Learned-model acceptance tests must RUN, not skip (SMOKE §4p): the export from infra/scripts/models.sh xfeat.
[ -f .cache/models/xfeat_ref/xfeat_weights.atb ] || die "no XFeat export (run: infra/scripts/models.sh xfeat)"
# ...and so must the PGO oracle (Phase 2 exit-gate item): the 100 GTSAM cases from infra/scripts/models.sh pgo-oracle.
[ "$(ls .cache/oracle/pgo/*.graph 2>/dev/null | wc -l)" -eq 100 ] || die "no PGO oracle cases (run: infra/scripts/models.sh pgo-oracle)"
cmd "$S/core.sh dev    # configure, build, full ctest, with ARIADNE_REQUIRE_MODELS=1"
$S/core.sh dev bash -c "cmake -S /work -B /work/build/docker -G Ninja -DARIADNE_REQUIRE_OPENCV=ON -DCMAKE_SKIP_RPATH=ON \
  -DFETCHCONTENT_BASE_DIR=/work/.cache/fetchcontent-docker >/dev/null && cmake --build /work/build/docker --parallel 8 \
  && ARIADNE_XFEAT_REF=/work/.cache/models/xfeat_ref ARIADNE_PGO_ORACLE=/work/.cache/oracle/pgo ARIADNE_REQUIRE_MODELS=1 \
     ctest --test-dir /work/build/docker --output-on-failure --parallel 8" > "$BIG/ctest.log" 2>&1 \
  || { tail -30 "$BIG/ctest.log"; die "build or ctest failed"; }
grep -E "tests passed|tests failed" "$BIG/ctest.log" > "$G/ctest.txt"
cmd "$S/core.sh dev ctest -R '^(CollabProtocol|Serialization)\\.'"
$S/core.sh dev bash -c "ctest --test-dir /work/build/docker -R '^(CollabProtocol|Serialization)\\.' \
  --output-on-failure" > "$G/protocol_tests.txt" 2>&1 || die "protocol tests failed (see $G/protocol_tests.txt)"

# --- 1. sim_collab: clean (+ spool) and faults, in parallel, from the same bag -----------------------------
log "1. sim_collab clean + faults (parallel)"
collab() {   # $1 = faults (0|1), $2 = extra args
  $S/core.sh dev bash -c "$env_run $bin/ariadne_sim_collab --rec /work/$REC/rec --scene /work/$SCENE \
    --perception-config /work/configs/perception/sim_v1.yaml --slam-config /work/configs/slam/sim_v1.yaml \
    --collab-config /work/configs/collab/collab_v1.yaml --inject-faults $1 $2 --out /work/$G/sim_collab"
}
spool_args="--spool /work/$BIG/spool --recon-config /work/configs/recon/recon_v1.yaml"
cmd "ariadne_sim_collab --rec $REC/rec --scene $SCENE [sim_v1, collab_v1] --inject-faults 0 $spool_args --out $G/sim_collab"
cmd "ariadne_sim_collab ... --inject-faults 1 --out $G/sim_collab     # concurrently"
collab 0 "$spool_args" > "$BIG/collab.log" 2>&1 & p0=$!
collab 1 "" > "$BIG/collab_faults.log" 2>&1 & p1=$!
wait "$p0" || { tail -20 "$BIG/collab.log"; die "sim_collab (clean) failed"; }
wait "$p1" || { tail -20 "$BIG/collab_faults.log"; die "sim_collab (faults) failed"; }
C="$(one "$G"/sim_collab/"$scene_id"-2*)" F="$(one "$G"/sim_collab/"$scene_id"-faults-*)"
SPOOL="$BIG/spool/$(basename "$C")"
cmd "$S/check_collab_fault_identity.sh $C $F"
$S/check_collab_fault_identity.sh "$C" "$F" > /dev/null || die "fault identity FAIL ($F/fault_identity.txt)"

# --- 2. recon: prepare -> Kaggle GPU render -> score; curate the small outputs ------------------------------
log "2. recon prepare"
cmd "$S/recon.sh prepare $SPOOL $SCENE $C/recon_eval.yaml $BIG/recon"
$S/recon.sh prepare "$SPOOL" "$SCENE" "$C/recon_eval.yaml" "$BIG/recon" > "$BIG/recon_prepare.log" 2>&1 \
  || { tail -20 "$BIG/recon_prepare.log"; die "recon prepare failed"; }
pkg="$(sha256sum "$BIG/recon/package/render_package.npz" | cut -d' ' -f1)"
if [ "$mode" = full ]; then
  log "2. Kaggle render (remote GPU)"
  cmd "$S/kaggle.sh render $BIG/recon/package $BIG/render"
  $S/kaggle.sh render "$BIG/recon/package" "$BIG/render" > "$BIG/kaggle.log" 2>&1 \
    || { tail -20 "$BIG/kaggle.log"; die "Kaggle render failed"; }
  mkdir -p "$CACHE/$pkg" && cp "$BIG/render/renders.npz" "$BIG/render/remote.json" "$CACHE/$pkg/"
else
  log "2. render REUSED from $CACHE/$pkg (pre-merge)"
  [ -f "$CACHE/$pkg/renders.npz" ] && [ -f "$CACHE/$pkg/remote.json" ] \
    || die "render package $pkg has no cached render: reconstruction output changed, run the FULL gate"
  cmd "# pre-merge: render reused from $CACHE/$pkg (render package byte-identical to a fully rendered one)"
  mkdir -p "$BIG/render" && cp "$CACHE/$pkg/renders.npz" "$CACHE/$pkg/remote.json" "$BIG/render/"
  echo "render_reused_from: $CACHE/$pkg" >> "$G/mode.txt"
fi
log "2. recon score"
cmd "$S/recon.sh score $BIG/recon $BIG/render"
$S/recon.sh score "$BIG/recon" "$BIG/render" > "$BIG/recon_score.log" 2>&1 \
  || { tail -20 "$BIG/recon_score.log"; die "recon score failed"; }
RC="$G/recon/$(basename "$C")"
mkdir -p "$RC"
cp "$BIG"/recon/{prepare,score,manifest_prepare,manifest_score}.yaml "$BIG/recon/package/render_package.json" \
   "$BIG/render/remote.json" "$SPOOL/spool.yaml" "$RC/"
{
  echo "# sha256 of the large outputs kept in $BIG (not committed)"
  sha256sum "$SPOOL/spool.yaml" "$BIG/recon/fused_cloud_O0.ply" "$BIG/recon/package/render_package.npz" \
    "$BIG/render/renders.npz"
  echo "$( (cd "$SPOOL" && find . -type f ! -name spool.yaml -print0 | sort -z | xargs -0 sha256sum) \
    | sha256sum | cut -d' ' -f1)  spool_files_except_yaml (sha256 of the sorted per-file sha256 list)"
} > "$RC/checksums.sha256"

# --- 3. mission x3 + eval -----------------------------------------------------------------------------------
log "3. mission merged / agent 0 / agent 1"
sha="$(sha256sum "$SPOOL/spool.yaml" | cut -d' ' -f1)"
cmd "for ag in merged 0 1: ariadne_mission --spool $SPOOL --scene $SCENE --config configs/mission/mission_v1.yaml --out $G/mission --agents \$ag"
$S/core.sh dev bash -c "for ag in merged 0 1; do $env_run ARIADNE_SPOOL_SHA256=$sha $bin/ariadne_mission \
  --spool /work/$SPOOL --scene /work/$SCENE --config /work/configs/mission/mission_v1.yaml \
  --out /work/$G/mission --agents \$ag || exit 1; done" > "$BIG/mission.log" 2>&1 \
  || { tail -20 "$BIG/mission.log"; die "mission failed"; }
M="$(one "$G"/mission/"$scene_id"-2*)" M0="$(one "$G"/mission/"$scene_id"-agent0only-*)"
M1="$(one "$G"/mission/"$scene_id"-agent1only-*)"
for r in "$M0" "$M1"; do
  cmd "$S/recon.sh mission-eval $r $SCENE $C"
  $S/recon.sh mission-eval "$r" "$SCENE" "$C" >> "$BIG/mission_eval.log" 2>&1 || die "mission-eval $r failed"
done
cmd "$S/recon.sh mission-eval $M $SCENE $C $M0 $M1"
$S/recon.sh mission-eval "$M" "$SCENE" "$C" "$M0" "$M1" >> "$BIG/mission_eval.log" 2>&1 || die "mission-eval $M failed"

# --- 4. report (§30.2) and 5. console -----------------------------------------------------------------------
log "4. report"
RP="$G/report/$(basename "$C")"
cmd "$S/report.sh $C $RC $M $SCENE $RP $M0 $M1"
rep_dirty_ok="${DIRTY_OK:-0}"; [ "$mode" = premerge ] && rep_dirty_ok=1
DIRTY_OK="$rep_dirty_ok" $S/report.sh "$C" "$RC" "$M" "$SCENE" "$RP" "$M0" "$M1" > "$BIG/report.log" 2>&1 \
  || { tail -20 "$BIG/report.log"; die "report failed"; }
log "5. console check"
cmd "$S/console.sh check $C $M $SCENE"
$S/console.sh check "$C" "$M" "$SCENE" > "$G/console_check.txt" 2>&1 || die "console check FAIL ($G/console_check.txt)"

# --- 6. the gate ----------------------------------------------------------------------------------------------
log "6. gate"
cmd "python -m analysis.phase1_gate --gate $G --big $BIG --config configs/benchmark/phase1_gate.yaml"
docker run --rm -u "$(id -u):$(id -g)" -v "$REPO_ROOT:/work:ro" -v "$REPO_ROOT/$G:/work/$G" -w /work \
  -e PYTHONPATH=/work/python ariadne-analysis:1 \
  python -m analysis.phase1_gate --gate "$G" --big "$BIG" --config configs/benchmark/phase1_gate.yaml \
  > "$G/gate.txt" 2>&1 || true
cat "$G/gate.txt"
grep -q '^VERDICT PASS' "$G/gate.txt" || die "gate FAIL ($G/gate.txt)"
log "PASS: $G"
